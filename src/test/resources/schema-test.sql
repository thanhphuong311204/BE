-- H2 only: existing MySQL account/profile columns plus the approved phone migration.
-- BIGINT on H2 cannot reproduce the entire MySQL UNSIGNED numeric range.
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL CONSTRAINT uq_users_email UNIQUE,
 phone_number VARCHAR(20) CONSTRAINT uq_users_phone_number UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 preferred_language_id BIGINT,
 status ENUM('ACTIVE','INACTIVE','SUSPENDED') DEFAULT 'ACTIVE' NOT NULL,
 email_verified BOOLEAN DEFAULT FALSE NOT NULL,
 email_verified_at TIMESTAMP,
 last_login_at TIMESTAMP,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 deleted_at TIMESTAMP
);
CREATE TABLE user_profiles (
 user_id BIGINT PRIMARY KEY,
 full_name VARCHAR(150) NOT NULL,
 avatar_url VARCHAR(1000),
 date_of_birth DATE,
 gender ENUM('FEMALE','MALE','OTHER','PREFER_NOT_TO_SAY'),
 bio VARCHAR(500),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
