-- H2 only: existing MySQL account/profile columns plus the approved phone migration.
-- BIGINT on H2 cannot reproduce the entire MySQL UNSIGNED numeric range.
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL CONSTRAINT uq_users_email UNIQUE,
 phone_number VARCHAR(20) CONSTRAINT uq_users_phone_number UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 preferred_language_id BIGINT,
 status ENUM('ACTIVE','INACTIVE','SUSPENDED') DEFAULT 'ACTIVE' NOT NULL,
 email_verified BOOLEAN DEFAULT FALSE NOT NULL,
 email_verified_at TIMESTAMP,
 last_login_at TIMESTAMP,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 deleted_at TIMESTAMP
);
CREATE TABLE user_profiles (
 user_id BIGINT PRIMARY KEY,
 full_name VARCHAR(150) NOT NULL,
 avatar_url VARCHAR(1000),
 date_of_birth DATE,
 gender ENUM('FEMALE','MALE','OTHER','PREFER_NOT_TO_SAY'),
 bio VARCHAR(500),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE languages (
		id BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

		code VARCHAR(10) NOT NULL,
		name VARCHAR(100) NOT NULL,
		native_name VARCHAR(100) NOT NULL,

		is_default BOOLEAN NOT NULL DEFAULT FALSE,
		is_active BOOLEAN NOT NULL DEFAULT TRUE,

		created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
		updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
			,

		CONSTRAINT uq_languages_code UNIQUE (code)
	);

CREATE TABLE styles (
		id BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		code VARCHAR(100) NOT NULL UNIQUE,
		is_active BOOLEAN NOT NULL DEFAULT TRUE,
		sort_order INT  NOT NULL DEFAULT 0,
		created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
		updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP

	);

CREATE TABLE style_translations (
		style_id BIGINT  NOT NULL,
		language_id BIGINT  NOT NULL,
		name VARCHAR(100) NOT NULL,
		description VARCHAR(500) NULL,

		PRIMARY KEY (style_id, language_id),

		FOREIGN KEY (style_id)
			REFERENCES styles(id)
			ON DELETE CASCADE,

		FOREIGN KEY (language_id)
			REFERENCES languages(id)
			ON DELETE CASCADE
	);

CREATE TABLE colors (
		id BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		code VARCHAR(50) NOT NULL UNIQUE,
		hex_code CHAR(7) NULL,
		is_active BOOLEAN NOT NULL DEFAULT TRUE,
		sort_order INT  NOT NULL DEFAULT 0,
		created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
		updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP

	);

CREATE TABLE color_translations (
		color_id BIGINT  NOT NULL,
		language_id BIGINT  NOT NULL,
		name VARCHAR(100) NOT NULL,

		PRIMARY KEY (color_id, language_id),

		FOREIGN KEY (color_id)
			REFERENCES colors(id)
			ON DELETE CASCADE,

		FOREIGN KEY (language_id)
			REFERENCES languages(id)
			ON DELETE CASCADE
	);

CREATE TABLE occasions (
		id BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		code VARCHAR(100) NOT NULL UNIQUE,
		is_active BOOLEAN NOT NULL DEFAULT TRUE,
		sort_order INT  NOT NULL DEFAULT 0,
		created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
		updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP

	);

CREATE TABLE occasion_translations (
		occasion_id BIGINT  NOT NULL,
		language_id BIGINT  NOT NULL,
		name VARCHAR(100) NOT NULL,
		description VARCHAR(500) NULL,

		PRIMARY KEY (occasion_id, language_id),

		FOREIGN KEY (occasion_id)
			REFERENCES occasions(id)
			ON DELETE CASCADE,

		FOREIGN KEY (language_id)
			REFERENCES languages(id)
			ON DELETE CASCADE
	);

CREATE TABLE user_style_preferences (
    user_id BIGINT  NOT NULL,
    status ENUM('NOT_STARTED', 'SKIPPED', 'COMPLETED')
        NOT NULL DEFAULT 'NOT_STARTED',
    completed_at TIMESTAMP NULL DEFAULT NULL,
    skipped_at TIMESTAMP NULL DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ,
    PRIMARY KEY (user_id),
    CONSTRAINT fk_usp_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE ON UPDATE RESTRICT
);

CREATE TABLE user_preferred_styles (
    user_id BIGINT  NOT NULL,
    style_id BIGINT  NOT NULL,
    PRIMARY KEY (user_id, style_id),
    INDEX idx_ups_style (style_id),
    CONSTRAINT fk_ups_preferences FOREIGN KEY (user_id)
        REFERENCES user_style_preferences(user_id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_ups_style FOREIGN KEY (style_id)
        REFERENCES styles(id) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE user_preferred_colors (
    user_id BIGINT  NOT NULL,
    color_id BIGINT  NOT NULL,
    PRIMARY KEY (user_id, color_id),
    INDEX idx_upc_color (color_id),
    CONSTRAINT fk_upc_preferences FOREIGN KEY (user_id)
        REFERENCES user_style_preferences(user_id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_upc_color FOREIGN KEY (color_id)
        REFERENCES colors(id) ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE TABLE user_preferred_occasions (
    user_id BIGINT  NOT NULL,
    occasion_id BIGINT  NOT NULL,
    PRIMARY KEY (user_id, occasion_id),
    INDEX idx_upo_occasion (occasion_id),
    CONSTRAINT fk_upo_preferences FOREIGN KEY (user_id)
        REFERENCES user_style_preferences(user_id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_upo_occasion FOREIGN KEY (occasion_id)
        REFERENCES occasions(id) ON DELETE RESTRICT ON UPDATE RESTRICT
);

