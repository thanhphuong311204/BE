CREATE TABLE chat_conversations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,
 title VARCHAR(120) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_chat_conversations_owner_updated ON chat_conversations(user_id,updated_at,id);
CREATE TABLE chat_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id BIGINT NOT NULL,
 role VARCHAR(9) NOT NULL CHECK(role IN ('USER','ASSISTANT')),
 content TEXT NOT NULL,
 content_blocks CLOB NULL,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY (conversation_id) REFERENCES chat_conversations(id) ON DELETE CASCADE
);
CREATE INDEX idx_chat_messages_conversation_id ON chat_messages(conversation_id,id);
CREATE INDEX idx_chat_messages_conversation_created ON chat_messages(conversation_id,created_at,id);

CREATE TABLE chat_requests (
 user_id BIGINT NOT NULL,
 request_id VARCHAR(64) NOT NULL,
 fingerprint VARCHAR(64) NOT NULL,
 response TEXT NULL,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 PRIMARY KEY(user_id,request_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
